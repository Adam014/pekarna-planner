import { z } from "zod";
import { RESERVATION_STATUSES } from "../domain/reservation";

/** A product and how many pieces; the same product twice is refused. */
export const orderItems = z
  .array(
    z.object({
      productId: z.uuid(),
      quantity: z.int().min(1).max(999),
    }),
  )
  .min(1)
  .max(50)
  .refine(
    (items) => new Set(items.map((i) => i.productId)).size === items.length,
    { message: "Each product only once" },
  );

/** Pickup time as HH:MM; the column is a Postgres `time`. */
const pickupTime = z.string().regex(/^([01]\d|2[0-3]):[0-5]\d$/);

/** What staff and the public form send for a new reservation (R1, R2). */
export const reservationInput = z.object({
  customerName: z.string().trim().min(1).max(100),
  phone: z.string().max(40),
  pickupDate: z.iso.date(),
  pickupTime: pickupTime.optional(),
  note: z.string().trim().max(500).optional(),
  items: orderItems,
  /** Generated by the form when it opens, so a double submit saves once. */
  idempotencyKey: z.uuid(),
});
export type ReservationInput = z.infer<typeof reservationInput>;

/** What the owner sends for a standing order (R7). */
export const standingOrderInput = z.object({
  customerName: z.string().trim().min(1).max(100),
  phone: z.string().max(40),
  weekdays: z
    .array(z.int().min(1).max(7))
    .min(1)
    .refine((days) => new Set(days).size === days.length, {
      message: "Each weekday only once",
    }),
  pickupTime: pickupTime.optional(),
  note: z.string().trim().max(500).optional(),
  items: orderItems,
});
export type StandingOrderInput = z.infer<typeof standingOrderInput>;

/** Staff mark a reservation on "Dnes" (R5). */
export const statusInput = z.object({
  reservationId: z.uuid(),
  status: z.enum(RESERVATION_STATUSES),
});

/** The id of a standing order being edited or ended. */
export const standingOrderId = z.uuid();
